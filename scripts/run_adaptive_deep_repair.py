"""Run deep_repair_loop with the provider-agnostic adaptive runtime layer."""
from __future__ import annotations

import json
import runpy
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADAPTIVE = ROOT / "scripts" / "adaptive_runtime"
SCRIPTS = ROOT / "scripts"
HEALTH_CONFIG = ROOT / "health-config.json"
sys.path.insert(0, str(ADAPTIVE))
sys.path.insert(1, str(SCRIPTS))

import runtime_repair  # noqa: E402
from repair_identity_gate import automatic_repair_identity_gate  # noqa: E402

loaded = Path(runtime_repair.__file__).resolve()
expected = (ADAPTIVE / "runtime_repair.py").resolve()
if loaded != expected:
    raise SystemExit(f"adaptive runtime layer not loaded: {loaded} != {expected}")

# Deep repair must not confuse presentation limits with validation depth. The
# normal config keeps routine probes cheap, while the repair pass may inspect up
# to ten ranked mirrors for a fixture. health_check still stops early as soon as
# a current playable >=720p media endpoint is proven, so healthy providers do
# not pay the full ten-probe budget.
health_config = json.loads(HEALTH_CONFIG.read_text(encoding="utf-8"))
deep_config = health_config.setdefault("modes", {}).setdefault("deep", {})
deep_config["max_streams_to_probe"] = max(10, int(deep_config.get("max_streams_to_probe") or 1))
deep_config["probe_streams_adaptively"] = True
HEALTH_CONFIG.write_text(json.dumps(health_config, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

# The adaptive runtime module still owns ranking and before/after comparison.
# Promotion adds a second, fail-closed invariant: newly generated bytes may
# replace their parent only when every playable fixture is positively tied to
# the requested work and has no duration/content contradiction.
_base_compare_results = runtime_repair.compare_results


def _identity_safe_compare_results(parent: dict, repaired: dict) -> tuple[bool, str]:
    accepted, reason = _base_compare_results(parent, repaired)
    if not accepted:
        return accepted, reason
    identity_ok, identity_reason = automatic_repair_identity_gate(repaired)
    if not identity_ok:
        return False, identity_reason
    return True, reason


runtime_repair.compare_results = _identity_safe_compare_results

# Do not force --max-rounds=0 anymore. deep_repair_loop now uses the configured
# bounded round count, while promotion is protected by the identity gate above.
sys.argv[0] = str(SCRIPTS / "deep_repair_loop.py")
runpy.run_path(sys.argv[0], run_name="__main__")
